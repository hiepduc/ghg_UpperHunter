def correlation(x, y):
    """Pearson correlation, ignoring NaN."""
    mask = np.isfinite(x) & np.isfinite(y)

    if np.sum(mask) < 2:
        return np.nan

    return np.corrcoef(x[mask], y[mask])[0, 1]


def calculate_metrics(obs, pred):
    """Calculate comparison statistics."""

    mask = np.isfinite(obs) & np.isfinite(pred)

    obs = np.asarray(obs)[mask]
    pred = np.asarray(pred)[mask]

    n = len(obs)

    if n == 0:
        return {
            "N": 0,
            "R": np.nan,
            "R2": np.nan,
            "Bias": np.nan,
            "RMSE": np.nan,
            "MAE": np.nan,
            "FAC2": np.nan,
            "Mean_obs": np.nan,
            "Mean_pred": np.nan,
        }

    diff = pred - obs

    r = correlation(obs, pred)

    # FAC2:
    # prediction / observation between 0.5 and 2
    valid_fac = obs > 0

    if np.any(valid_fac):
        ratio = pred[valid_fac] / obs[valid_fac]
        fac2 = np.mean(
            (ratio >= 0.5) &
            (ratio <= 2.0)
        )
    else:
        fac2 = np.nan

    return {
        "N": n,
        "R": r,
        "R2": r ** 2 if np.isfinite(r) else np.nan,
        "Bias": np.mean(diff),
        "RMSE": np.sqrt(np.mean(diff ** 2)),
        "MAE": np.mean(np.abs(diff)),
        "FAC2": fac2,
        "Mean_obs": np.mean(obs),
        "Mean_pred": np.mean(pred),
    }


def load_prior_emissions():
    """
    Read prior mine emissions.

    Expected input column:
        Facility_code_name
        gCH4/s
    """

    print("\n" + "=" * 80)
    print("READING PRIOR MINE EMISSIONS")
    print("=" * 80)

    df = pd.read_csv(PRIOR_EMISSION_FILE)

    print("\nPrior emission columns:")
    print(df.columns.tolist())

    # Clean mine names
    df["Facility_code_name"] = (
        df["Facility_code_name"]
        .astype(str)
        .str.strip()
    )

    # Select requested mines
    mine_df = df[
        df["Facility_code_name"].isin(MINES)
    ].copy()

    if len(mine_df) != len(MINES):
        found = set(mine_df["Facility_code_name"])
        missing = [m for m in MINES if m not in found]

        raise RuntimeError(
            f"Missing prior emissions for mines: {missing}"
        )

    # Preserve exact mine order
    mine_df["mine_order"] = mine_df[
        "Facility_code_name"
    ].map({m: i for i, m in enumerate(MINES)})

    mine_df = mine_df.sort_values("mine_order")

    # g/s -> kg/s
    prior_kg_s = (
        mine_df["gCH4/s"].astype(float).values
        * G_TO_KG
    )

    print("\nPrior emissions:")
    for mine, emission in zip(MINES, prior_kg_s):
        print(
            f"{mine:>5s} : "
            f"{emission:12.6f} kg CH4/s "
            f"({emission * 1000:10.2f} g CH4/s)"
        )

    print("-" * 80)

    print(
        f"TOTAL : "
        f"{prior_kg_s.sum():12.6f} kg CH4/s "
        f"({prior_kg_s.sum() * 1000:10.2f} g CH4/s)"
    )

    return prior_kg_s


def load_posterior_scaling():
    """
    Read posterior mean daily scaling factors.

    Expected output from blocked MCMC:

        mcmc_daily_scaling.csv

    Expected columns are either:

        date, OC1, OC2, ..., OC13

    or:

        date + 13 mine columns
    """

    print("\n" + "=" * 80)
    print("READING POSTERIOR DAILY SCALING FACTORS")
    print("=" * 80)

    df = pd.read_csv(POSTERIOR_SCALING_FILE)

    print("\nPosterior scaling columns:")
    print(df.columns.tolist())

    # ---------------------------------------------------------
    # Identify date column
    # ---------------------------------------------------------

    date_candidates = [
        c for c in df.columns
        if c.lower() in ["date", "datetime", "day"]
    ]

    if not date_candidates:
        raise RuntimeError(
            "Could not identify date column in "
            f"{POSTERIOR_SCALING_FILE}"
        )

    date_col = date_candidates[0]

    df[date_col] = pd.to_datetime(df[date_col])

    # ---------------------------------------------------------
    # Check mine columns
    # ---------------------------------------------------------

    missing = [
        mine for mine in MINES
        if mine not in df.columns
    ]

    if missing:
        raise RuntimeError(
            "Posterior scaling file is missing mines: "
            f"{missing}"
        )

    # ---------------------------------------------------------
    # Sort by date
    # ---------------------------------------------------------

    df = df.sort_values(date_col).reset_index(drop=True)

    # ---------------------------------------------------------
    # Check expected 27 days
    # ---------------------------------------------------------

    expected_dates = pd.date_range(
        "2026-01-05",
        "2026-01-31",
        freq="D"
    )

    if len(df) != 27:
        print(
            f"\nWARNING: posterior file contains "
            f"{len(df)} rows, expected 27."
        )

    # ---------------------------------------------------------
    # Print posterior means
    # ---------------------------------------------------------

    print("\nPosterior scaling factor range:")

    for mine in MINES:
        values = df[mine].astype(float).values

        print(
            f"{mine:>5s} : "
            f"mean={np.mean(values):8.4f}  "
            f"min={np.min(values):8.4f}  "
            f"max={np.max(values):8.4f}"
        )

    return df, date_col


